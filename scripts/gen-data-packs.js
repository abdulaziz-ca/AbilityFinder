#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const ROOT = path.join(__dirname, "..");
const PACKS = ["AB", "BC", "ON", "SK", "MB", "NB", "NS", "PE", "NL", "QC"];
const NAMES = ["Alberta", "British Columbia", "Ontario", "Saskatchewan", "Manitoba", "New Brunswick", "Nova Scotia", "Prince Edward Island", "Newfoundland and Labrador", "Quebec"];
// Keep executable fields (URLs chosen from answers) as code, never JSON strings.
function serialize(value) {
  if (typeof value === "function") return value.toString();
  if (Array.isArray(value)) return `[${value.map(serialize).join(",")} ]`;
  if (value && typeof value === "object") return `{${Object.entries(value).map(([k, v]) => `${JSON.stringify(k)}:${serialize(v)}`).join(",")}}`;
  return JSON.stringify(value);
}
function generate() {
  const source = fs.readFileSync(path.join(ROOT, "public/data.js"), "utf8");
  const ctx = vm.createContext({});
  vm.runInContext(source + "\nglobalThis.catalogue = {BENEFITS, CITIES_BY_PROVINCE, ON_REGIONS};", ctx);
  const { BENEFITS, CITIES_BY_PROVINCE, ON_REGIONS } = ctx.catalogue;
  const packs = Object.fromEntries(PACKS.map(p => [p, []]));
  const index = BENEFITS.map(b => {
    const owners = ["Federal", "Your community"].includes(b.level) ? [] : PACKS.filter((p, i) => b.level === NAMES[i] || CITIES_BY_PROVINCE[p].includes(b.level) || (p === "BC" && b.level === "Metro Vancouver") || (p === "ON" && ON_REGIONS.includes(b.level)) || (p === "AB" && b.level === "Spruce Grove area"));
    if (!["Federal", "Your community"].includes(b.level) && !owners.length) throw new Error(`No pack for ${b.id}: ${b.level}`);
    for (const p of owners) packs[p].push(b);
    return [b.id, b.level, owners[0] || null];
  });
  const begin = source.indexOf("const BENEFITS = [");
  const end = source.indexOf("\n];", begin) + 3;
  if (begin < 0 || end < begin) throw new Error("Cannot locate BENEFITS declaration");
  const core = source.slice(0, begin) + `const BENEFITS = ${serialize(BENEFITS.filter(b => ["Federal", "Your community"].includes(b.level)))};` + source.slice(end);
  const exports = [...core.matchAll(/^const (\w+) =/gm)].map(m => m[1]);
  exports.push("glossaryTermsFor", "BENEFIT_INDEX", "AF_ADD_PACK", "AF_LOADED_PACKS");
  const runtime = `\nconst BENEFIT_INDEX = ${JSON.stringify(index)};\nconst AF_LOADED_PACKS = new Set();\nfunction AF_ADD_PACK(province, records) {\n  const ids = new Set(BENEFITS.map(b => b.id));\n  for (const b of records) if (!ids.has(b.id)) { BENEFITS.push(b); ids.add(b.id); }\n  const order = new Map(BENEFIT_INDEX.map((row, i) => [row[0], i]));\n  BENEFITS.sort((a, b) => order.get(a.id) - order.get(b.id));\n  AF_LOADED_PACKS.add(province);\n}\n`;
  // Properties, not global lexical declarations: the unchanged full data.js can
  // shadow them when the app's DATA_PACKS kill switch selects the fallback.
  const files = { "data-core.js": `// Generated by npm run gen:packs. Edit public/data.js instead.\n(() => {\n${core}\n${runtime}\nObject.assign(globalThis, {${exports.join(",")}});\n})();\n` };
  for (const p of PACKS) files[`data-pack-${p}.js`] = `// Generated by npm run gen:packs. Edit public/data.js instead.\nAF_ADD_PACK(${JSON.stringify(p)}, ${serialize(packs[p])});\n`;
  return files;
}
if (require.main === module) for (const [name, text] of Object.entries(generate())) {
  fs.writeFileSync(path.join(ROOT, "public", name), text);
  console.log(`${name}: ${Buffer.byteLength(text)} bytes`);
}
module.exports = { generate, serialize, PACKS };
